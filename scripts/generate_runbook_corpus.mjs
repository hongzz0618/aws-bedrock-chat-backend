import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse } from "yaml";
import { runbookTokens } from "../src-ts/runbookTokens.cjs";

const sourceDirectory = fileURLToPath(new URL("../docs/runbooks/", import.meta.url));
const corpusFile = new URL("../src-ts/runbookCorpus.ts", import.meta.url);
const idPattern = /^[a-z0-9]+(?:[.-][a-z0-9]+)*$/;

function readMetadata(yaml, expectedKeys, location) {
  let metadata;
  try {
    metadata = parse(yaml);
  } catch (error) {
    throw new Error(`${location}: invalid YAML metadata: ${error.message}`);
  }
  if (!metadata || typeof metadata !== "object" ||
      Object.keys(metadata).length !== expectedKeys.length ||
      !expectedKeys.every((key) => Object.hasOwn(metadata, key))) {
    throw new Error(`${location}: expected metadata fields ${expectedKeys.join(", ")}`);
  }
  return metadata;
}

export function loadRunbooks(directory = sourceDirectory) {
  const filenames = readdirSync(directory).filter((filename) => filename.endsWith(".md")).sort();
  if (!filenames.length) throw new Error("No Markdown runbooks found");

  const documentIds = new Set();
  const chunkIds = new Set();
  const chunks = [];
  for (const filename of filenames) {
    const markdown = readFileSync(resolve(directory, filename), "utf8").replaceAll("\r\n", "\n");
    const [header, ...sections] = markdown.split(/^## /m);
    const document = /^---\n([\s\S]+?)\n---\n\n# (.+)\n\s*$/.exec(header);
    if (!document || !document[2].trim() || !sections.length) {
      throw new Error(`${filename}: expected document metadata, a title and at least one section`);
    }

    const { documentId, version } = readMetadata(document[1], ["documentId", "version"], filename);
    if (typeof documentId !== "string" || !idPattern.test(documentId)) {
      throw new Error(`${filename}: invalid documentId`);
    }
    if (typeof version !== "string" || !/^[1-9][0-9]*$/.test(version)) {
      throw new Error(`${filename}: version must be a quoted positive integer`);
    }
    if (documentIds.has(documentId)) throw new Error(`${filename}: duplicate documentId "${documentId}"`);
    documentIds.add(documentId);

    const title = document[2].trim();
    for (const [index, section] of sections.entries()) {
      const location = `${filename} (section ${index + 1})`;
      const entry = /^(.+)\n<!--\n([\s\S]+?)\n-->\n\n([\s\S]*)$/.exec(section);
      if (!entry || !entry[1].trim() || !entry[3].trim()) {
        throw new Error(`${location}: expected a heading, a metadata comment and excerpt text`);
      }
      const { chunkId, keywords } = readMetadata(entry[2], ["chunkId", "keywords"], location);
      if (typeof chunkId !== "string" || !idPattern.test(chunkId) || !chunkId.startsWith(`${documentId}.`)) {
        throw new Error(`${location}: chunkId must be a valid ID starting with "${documentId}."`);
      }
      if (chunkIds.has(chunkId)) throw new Error(`${location}: duplicate chunkId "${chunkId}"`);
      if (!Array.isArray(keywords) || keywords.some((keyword) =>
        typeof keyword !== "string" || keyword !== keyword.trim() || runbookTokens(keyword).length === 0)) {
        throw new Error(`${location}: keywords must be a list of trimmed phrases with at least one searchable word each`);
      }
      chunkIds.add(chunkId);
      chunks.push({ documentId, version, chunkId, title, section: entry[1].trim(), keywords, text: entry[3].trim() });
    }
  }
  return chunks;
}

export function generateCorpus(directory) {
  const entries = loadRunbooks(directory).map(({ documentId, version, chunkId, title, section, keywords, text }) => `  {
    documentId: ${JSON.stringify(documentId)}, version: ${JSON.stringify(version)}, chunkId: ${JSON.stringify(chunkId)},
    title: ${JSON.stringify(title)}, section: ${JSON.stringify(section)},
    keywords: [${keywords.map((keyword) => JSON.stringify(keyword)).join(", ")}],
    text: ${JSON.stringify(text)},
  },`);
  return `// Generated by npm run runbooks:generate from docs/runbooks/*.md.
export interface RunbookChunk {
  readonly documentId: string;
  readonly version: string;
  readonly chunkId: string;
  readonly title: string;
  readonly section: string;
  readonly text: string;
  readonly keywords?: readonly string[];
}

export const runbookCorpus: readonly RunbookChunk[] = Object.freeze([
${entries.join("\n")}
].map((chunk) => Object.freeze({ ...chunk, keywords: Object.freeze(chunk.keywords) })));
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    writeFileSync(corpusFile, generateCorpus());
    console.log("Generated src-ts/runbookCorpus.ts");
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
